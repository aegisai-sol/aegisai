"""JS claim-server emittedUntil (token/scripts/mine-rules.mjs) == Python mine_emit.emitted_until.

Vectors are generated by the JS ceiling the live claim server enforces, so both
stacks agree to the base unit on how much AGIS the halving schedule allows.
"""
import json
from pathlib import Path

from aegis_miner import mine_emit as me

V = json.loads((Path(__file__).parent / "emission_schedule_vectors.json").read_text())


def test_constants_match_js():
    assert V["eraSeconds"] == me.EMISSION_ERA_SECONDS
    assert int(V["rate0"]) == me.RATE0
    assert int(V["minePoolBase"]) == me.MINE_ALLOC_BASE


def test_emitted_until_matches_js_vectors():
    g = V["genesis"]
    assert len(V["cases"]) >= 15
    for c in V["cases"]:
        assert me.emitted_until(g + c["offset"], g) == int(c["emittedUntil"]), c


def test_schedule_never_exceeds_85pct_pool_and_halves():
    g = V["genesis"]
    vals = {c["offset"]: int(c["emittedUntil"]) for c in V["cases"]}
    assert max(vals.values()) < me.MINE_ALLOC_BASE
    era0 = vals[me.EMISSION_ERA_SECONDS]
    era1_only = vals[2 * me.EMISSION_ERA_SECONDS + 7] - era0 - me.emission_per_second(2) * 7
    assert era1_only == (me.RATE0 >> 1) * me.EMISSION_ERA_SECONDS  # era 1 rate = half of era 0
    assert 0 <= era0 - 2 * era1_only <= me.EMISSION_ERA_SECONDS  # ~half (integer floor)
